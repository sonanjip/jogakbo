package io.github.taehunkim.jogakbo.fetch

import io.github.taehunkim.jogakbo.audio.Cue
import org.json.JSONArray
import org.json.JSONObject
import org.jsoup.Jsoup
import org.jsoup.parser.Parser
import java.net.URI
import java.net.URLDecoder

/** A video's facts and subtitles. [cues] is empty when the video has no usable subtitle track. */
data class Video(
    val id: String,
    val title: String,
    val channel: String?,
    val description: String,
    val lengthSec: Long?,
    val published: String?,
    val captionLanguage: String?,
    val autoCaptions: Boolean,
    val cues: List<Cue>,
)

/** One subtitle track of a video. kind "asr" = generated by speech recognition. */
data class CaptionTrack(val baseUrl: String, val language: String, val kind: String?, val name: String?) {
    val auto: Boolean get() = kind == "asr"
}

/**
 * Reads a YouTube video's title, description and subtitles without an API key: the watch page carries the facts
 * and an API key, the player API (as the Android app asks) lists the subtitle tracks, and the timed-text URL of
 * the chosen track gives the lines. YouTube changes these pages now and then; everything that depends on their
 * shape is in this file (and covered by tests with saved answers).
 */
class YouTubeFetcher(private val http: HttpClient) {
    suspend fun fetch(url: String): Video {
        val id = videoId(url) ?: throw FetchException("not a YouTube video link")
        val watch = runCatching { http.get("https://www.youtube.com/watch?v=$id&hl=en", CONSENT) }.getOrNull()
        val page = watch?.takeIf { it.code == 200 }?.body.orEmpty()
        val fromPage = playerResponse(page)
        val key = Regex("\"INNERTUBE_API_KEY\":\"([^\"]+)\"").find(page)?.groupValues?.get(1) ?: DEFAULT_KEY
        val fromApi = runCatching {
            val body = JSONObject().put("context", JSONObject().put("client", JSONObject().put("clientName", "ANDROID").put("clientVersion", ANDROID_VERSION)))
                .put("videoId", id).toString()
            http.postJson("https://www.youtube.com/youtubei/v1/player?key=$key", body, CONSENT).takeIf { it.code == 200 }?.body?.let { JSONObject(it) }
        }.getOrNull()
        val details = (fromApi?.optJSONObject("videoDetails") ?: fromPage?.optJSONObject("videoDetails"))
        if (details == null && fromPage == null && fromApi == null) throw FetchException("YouTube did not answer (${watch?.code ?: "no connection"})")
        val status = (fromApi ?: fromPage)?.optJSONObject("playabilityStatus")?.optString("status")
        if (details == null) throw FetchException("video unavailable (${status ?: "unknown"})")

        val tracks = tracks(fromApi).ifEmpty { tracks(fromPage) }
        val track = chooseTrack(tracks)
        val cues = track?.let { t ->
            runCatching { parseTimedText(http.get(stripFmt(t.baseUrl), CONSENT).body) }.getOrDefault(emptyList())
                .ifEmpty { runCatching { parseTimedText(http.get(stripFmt(t.baseUrl) + "&fmt=json3", CONSENT).body) }.getOrDefault(emptyList()) }
        }.orEmpty()
        val micro = fromPage?.optJSONObject("microformat")?.optJSONObject("playerMicroformatRenderer")
        return Video(
            id = id,
            title = details.optString("title").ifBlank { "YouTube $id" },
            channel = details.optString("author").ifBlank { null },
            description = details.optString("shortDescription"),
            lengthSec = details.optString("lengthSeconds").toLongOrNull(),
            published = micro?.optString("publishDate")?.ifBlank { null },
            captionLanguage = track?.language,
            autoCaptions = track?.auto == true,
            cues = mergeCues(cues),
        )
    }

    companion object {
        /** Skips the EU consent page. */
        private val CONSENT = mapOf("Cookie" to "CONSENT=YES+1; SOCS=CAI")
        private const val ANDROID_VERSION = "20.10.38"
        /** The public key of YouTube's web player (used when the watch page did not carry one). */
        private const val DEFAULT_KEY = "AIzaSyAO_FJ2SlqU8Q4STEHLGCilw_Y9_11qcW8"

        fun isYouTube(url: String): Boolean = videoId(url) != null

        /** The 11-character id of a video link (watch, youtu.be, shorts, live, embed; www, m and music hosts). */
        fun videoId(url: String): String? {
            val u = runCatching { URI(url.trim()) }.getOrNull() ?: return null
            val host = u.host?.lowercase()?.removePrefix("www.")?.removePrefix("m.")?.removePrefix("music.") ?: return null
            val path = u.path.orEmpty()
            val id = when (host) {
                "youtu.be" -> path.trim('/').substringBefore('/')
                "youtube.com", "youtube-nocookie.com" -> when {
                    path == "/watch" -> query(u.rawQuery)["v"]
                    path.startsWith("/shorts/") || path.startsWith("/live/") || path.startsWith("/embed/") || path.startsWith("/v/") ->
                        path.split('/').getOrNull(2)
                    else -> null
                }
                else -> null
            }
            return id?.takeIf { Regex("[A-Za-z0-9_-]{11}").matches(it) }
        }

        private fun query(raw: String?): Map<String, String> = raw.orEmpty().split('&').mapNotNull { p ->
            val i = p.indexOf('=')
            if (i <= 0) null else p.substring(0, i) to URLDecoder.decode(p.substring(i + 1), "UTF-8")
        }.toMap()

        /** The `ytInitialPlayerResponse` object embedded in a watch page. */
        fun playerResponse(page: String): JSONObject? {
            val start = Regex("ytInitialPlayerResponse\\s*=\\s*\\{").find(page) ?: return null
            val open = start.range.last
            val end = matchingBrace(page, open) ?: return null
            return runCatching { JSONObject(page.substring(open, end + 1)) }.getOrNull()
        }

        private fun matchingBrace(s: String, open: Int): Int? {
            var depth = 0
            var inString = false
            var i = open
            while (i < s.length) {
                val c = s[i]
                if (inString) {
                    if (c == '\\') i++ else if (c == '"') inString = false
                } else when (c) {
                    '"' -> inString = true
                    '{' -> depth++
                    '}' -> { depth--; if (depth == 0) return i }
                }
                i++
            }
            return null
        }

        fun tracks(player: JSONObject?): List<CaptionTrack> {
            val arr = player?.optJSONObject("captions")?.optJSONObject("playerCaptionsTracklistRenderer")?.optJSONArray("captionTracks") ?: return emptyList()
            return (0 until arr.length()).mapNotNull { i ->
                val o = arr.optJSONObject(i) ?: return@mapNotNull null
                val name = o.optJSONObject("name")?.let { n -> n.optString("simpleText").ifBlank { n.optJSONArray("runs")?.optJSONObject(0)?.optString("text") } }
                CaptionTrack(o.optString("baseUrl").ifBlank { return@mapNotNull null }, o.optString("languageCode"), o.optString("kind").ifBlank { null }, name)
            }
        }

        /**
         * The spoken language is the language of the generated track (when there is one): a track written by
         * people in that language comes first, then the generated one, then any track written by people.
         */
        fun chooseTrack(tracks: List<CaptionTrack>): CaptionTrack? {
            val auto = tracks.firstOrNull { it.auto }
            val spoken = auto?.language?.substringBefore('-')
            return tracks.firstOrNull { !it.auto && spoken != null && it.language.substringBefore('-') == spoken }
                ?: auto ?: tracks.firstOrNull { !it.auto }
        }

        private fun stripFmt(url: String) = url.replace(Regex("&fmt=[^&]*"), "")

        /** Lines of a timed-text answer: json3, srv3 (`<p t d>`) or the classic `<text start dur>` XML. */
        fun parseTimedText(body: String): List<Cue> {
            val t = body.trimStart()
            if (t.startsWith("{")) {
                val events = JSONObject(t).optJSONArray("events") ?: JSONArray()
                return (0 until events.length()).mapNotNull { i ->
                    val e = events.optJSONObject(i) ?: return@mapNotNull null
                    val segs = e.optJSONArray("segs") ?: return@mapNotNull null
                    val text = (0 until segs.length()).joinToString("") { segs.optJSONObject(it)?.optString("utf8").orEmpty() }.replace('\n', ' ').trim()
                    if (text.isEmpty()) null else {
                        val s = e.optLong("tStartMs"); Cue(s, s + e.optLong("dDurationMs"), text)
                    }
                }
            }
            if (!t.startsWith("<")) return emptyList()
            val doc = Jsoup.parse(t, "", Parser.xmlParser())
            val classic = doc.select("text").mapNotNull { e ->
                val s = (e.attr("start").toDoubleOrNull() ?: return@mapNotNull null) * 1000
                val d = (e.attr("dur").toDoubleOrNull() ?: 0.0) * 1000
                val text = Parser.unescapeEntities(e.text(), false).replace('\n', ' ').trim()
                if (text.isEmpty()) null else Cue(s.toLong(), (s + d).toLong(), text)
            }
            if (classic.isNotEmpty()) return classic
            return doc.select("p").mapNotNull { e ->
                val s = e.attr("t").toLongOrNull() ?: return@mapNotNull null
                val text = e.text().replace('\n', ' ').trim()
                if (text.isEmpty()) null else Cue(s, s + (e.attr("d").toLongOrNull() ?: 0), text)
            }
        }

        /**
         * Generated subtitles arrive as overlapping fragments of a few words: joins them into lines that end at a
         * sentence end or after about [maxChars], so a line is worth tapping and reading.
         */
        fun mergeCues(cues: List<Cue>, maxChars: Int = 120): List<Cue> {
            val out = ArrayList<Cue>()
            var start = -1L; var end = 0L
            val sb = StringBuilder()
            for (c in cues.sortedBy { it.startMs }) {
                if (sb.isEmpty()) start = c.startMs
                if (sb.isNotEmpty()) sb.append(' ')
                sb.append(c.text.trim())
                end = maxOf(end, minOf(c.endMs, c.startMs + 10_000))
                val sentenceEnd = c.text.trimEnd().lastOrNull()?.let { it in ".!?。！？" } == true
                if (sentenceEnd || sb.length >= maxChars) {
                    out += Cue(start, end, sb.toString().replace(Regex("\\s+"), " ").trim()); sb.clear()
                }
            }
            if (sb.isNotEmpty()) out += Cue(start, end, sb.toString().replace(Regex("\\s+"), " ").trim())
            return out
        }
    }
}
